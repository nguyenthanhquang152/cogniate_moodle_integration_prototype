#!/usr/bin/env node
// Makes docs/human_review/flows.md from the "pack-data" JSON block in docs/human_review/explainer.html.
// So the explainer, the Markdown diagrams and the video use the same content.
// Usage: node docs/human_review/tools/build-md.mjs           write flows.md
//        node docs/human_review/tools/build-md.mjs --check   exit 1 if flows.md is out of date
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(dir, 'explainer.html'), 'utf8');
const block = html.match(/<script type="application\/json" id="pack-data">([\s\S]*?)<\/script>/);
if (!block) {
  console.error('explainer.html has no <script type="application/json" id="pack-data"> block.');
  process.exit(2);
}
const data = JSON.parse(block[1]);

// Mermaid breaks on ";" and "#" in message text.
const mm = (text) => text.replace(/;/g, ',').replace(/#/g, 'no. ');
const alias = (key) => key.toUpperCase();
// Heading anchor as GitHub makes it: lower case, drop punctuation, spaces to hyphens.
const slug = (heading) => heading.toLowerCase().replace(/[^\p{L}\p{N} -]/gu, '').replace(/ /g, '-');
const status = { qa: 'Proven by QA', pending: 'Pending final QA', author: 'Not verified by QA', planned: 'Planned, not tested yet', not: 'Not proven' };
const proof = (p) =>
  p.status === 'planned'
    ? `Status: **${status.planned}**. Planned proof: ${p.ids.map((id) => `\`${id}\``).join(', ')}. Result: after T7.`
    : `Status: **${status[p.status]}**. Evidence: ${p.ids.map((id) => `\`${id}\``).join(', ')}.`;

const out = [
  '# Key flows',
  '',
  `<!-- Made by docs/human_review/tools/build-md.mjs from explainer.html. Do not edit this file by hand. -->`,
  '',
  `Source: commit \`${data.meta.source}\`, ${data.meta.date}. The same diagrams are in [\`explainer.html\`](explainer.html) (tab Flows).`,
  '',
  data.meta.flowsNote,
  'The full technical diagrams are in [`docs/architecture/flows.md`](../architecture/flows.md).',
  '',
  '| # | Flow | People | Status |',
  '| --- | --- | --- | --- |',
  ...data.flows.map((f, i) => {
    const people = f.actors.filter((k) => data.actors[k].kind === 'person').map((k) => data.actors[k].name).join(', ');
    return `| ${i + 1} | [${f.title}](#${slug(`${i + 1}. ${f.title}`)}) | ${people} | ${status[f.proof.status]} |`;
  }),
  '',
];

data.flows.forEach((f, i) => {
  out.push(`## ${i + 1}. ${f.title}`, '', f.summary, '', '```mermaid', 'sequenceDiagram', '    autonumber');
  for (const key of f.actors) {
    const a = data.actors[key];
    out.push(`    ${a.kind === 'person' ? 'actor' : 'participant'} ${alias(key)} as ${a.name}`);
  }
  for (const st of f.steps) out.push(`    ${alias(st.from)}${st.reply ? '-->>' : '->>'}${alias(st.to)}: ${mm(st.label)}`);
  out.push('```', '');
  f.steps.forEach((st, k) => out.push(`${k + 1}. **${st.label}.** ${st.detail}`));
  out.push('', proof(f.proof), `Technical diagram: section ${f.ref} of \`docs/architecture/flows.md\`.`, '');
});

const text = out.join('\n');
const target = join(dir, 'flows.md');
if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== text) {
    console.error('flows.md is out of date. Run: node docs/human_review/tools/build-md.mjs');
    process.exit(1);
  }
  console.log('flows.md is up to date.');
} else {
  writeFileSync(target, text);
  console.log(`Wrote ${target} (${data.flows.length} flows).`);
}
